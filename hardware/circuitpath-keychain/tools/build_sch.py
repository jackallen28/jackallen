"""Build kicad/circuitpath-keychain.kicad_sch from design.py (netlist-accurate; connections are net labels).

python3 build_sch.py <out.kicad_sch>
"""
import copy
import os
import sys
import uuid

sys.path.insert(0, os.path.dirname(__file__))
from kiutils.schematic import Schematic
from kiutils.symbol import SymbolLib
from kiutils.items.schitems import SchematicSymbol, LocalLabel, NoConnect, SymbolProjectInstance, SymbolProjectPath
from kiutils.items.common import Position, Property, Effects, Font, TitleBlock
import design as D

SYMDIR = "/usr/share/kicad/symbols"
libs, cache = {}, {}


def lib_symbol(spec):
    if spec in cache:
        return cache[spec]
    lib, name = spec.split(":")
    if lib not in libs:
        libs[lib] = SymbolLib.from_file("%s/%s.kicad_sym" % (SYMDIR, lib))
    for s in libs[lib].symbols:
        if s.entryName == name:
            if s.extends:                      # flatten: embedded symbols may not use 'extends'
                parent = copy.deepcopy(next(q for q in libs[lib].symbols if q.entryName == s.extends))
                for u in parent.units:
                    u.entryName = name
                parent.entryName = name
                for prop in s.properties:
                    for pp in parent.properties:
                        if pp.key == prop.key:
                            pp.value = prop.value
                s = parent
            s.libraryNickname = lib
            cache[spec] = s
            return s
    raise SystemExit("symbol not found " + spec)


def pins_of(sym):
    out = []
    for u in sym.units:
        out.extend(u.pins)
    return out


def bbox(sym):
    ps = pins_of(sym)
    xs = [p.position.X for p in ps]
    ys = [p.position.Y for p in ps]
    return min(xs), max(xs), min(ys), max(ys)


def snap(v, g=2.54):
    return round(v / g) * g


def eff(size=1.27, hide=False):
    return Effects(font=Font(height=size, width=size), hide=hide)


def build(out):
    sch = Schematic.create_new()
    sch.paper.paperSize = "A1"
    sch.titleBlock = TitleBlock(title="CircuitPath Keychain", date="2026-10-30", revision="A",
                                company="Banyule Nillumbik Tech School (BNTS)",
                                comments={1: "ATmega32U4 (Arduino Leonardo/Micro compatible), USB-A plug + USB-C, 2x MAX7219, 77 LEDs",
                                          2: "Generated by tools/build_sch.py from tools/design.py - edit design.py, not this file"})
    sch.uuid = str(uuid.uuid4())
    root = sch.uuid
    placed = []

    # --- flow layout: ICs/connectors first, then passives, LEDs in their own block
    order = [p for p in D.PARTS if p["ref"][0] in "JUY" or p["ref"].startswith("SW")]
    order += [p for p in D.PARTS if p not in order and not p["fp"].startswith("LED_SMD")]
    cx, cy, rowh, X0, W = 30.0, 40.0, 0.0, 30.0, 560.0
    for p in order:
        sym = lib_symbol(p["sym"])
        x0, x1, y0, y1 = bbox(sym)
        w, h = (x1 - x0) + 50, (y1 - y0) + 24
        if cx + w > X0 + W:
            cx, cy, rowh = X0, cy + rowh, 0.0
        p["sch"] = (snap(cx - x0 + 25), snap(cy + y1 + 12))
        cx += w
        rowh = max(rowh, h)
    led_y0 = cy + rowh + 40
    leds = [p for p in D.PARTS if p["fp"].startswith("LED_SMD")]
    for p in leds:
        i, j = divmod(D.LEDS.index(next(l for l in D.LEDS if l["ref"] == p["ref"])), D.ROWS)
        p["sch"] = (snap(40 + i * 38), snap(led_y0 + j * 14))

    for p in D.PARTS:
        sym = lib_symbol(p["sym"])
        x, y = p["sch"]
        props = [
            Property("Reference", p["ref"], 0, Position(x, y - 2, 0), eff()),
            Property("Value", p["value"], 1, Position(x, y + 2, 0), eff()),
            Property("Footprint", p["fp"], 2, Position(x, y, 0), eff(hide=True)),
            Property("Datasheet", "~", 3, Position(x, y, 0), eff(hide=True)),
            Property("LCSC", p["lcsc"], 4, Position(x, y, 0), eff(hide=True)),
            Property("MPN", p["mpn"], 5, Position(x, y, 0), eff(hide=True)),
        ]
        inst = SchematicSymbol(libraryNickname=sym.libraryNickname, entryName=sym.entryName, position=Position(x, y, 0),
                               unit=1, inBom=p["lcsc"] != "", onBoard=True, dnp=False, properties=props, uuid=str(uuid.uuid4()))
        inst.pins = {pn.number: str(uuid.uuid4()) for pn in pins_of(sym)}
        inst.instances = [SymbolProjectInstance(name="circuitpath-keychain",
                                                paths=[SymbolProjectPath(sheetInstancePath="/" + root, reference=p["ref"], unit=1)])]
        sch.schematicSymbols.append(inst)
        for pn in pins_of(sym):
            net = p["pins"].get(pn.number)
            ax, ay = x + pn.position.X, y - pn.position.Y
            if net is None:
                sch.noConnects.append(NoConnect(position=Position(ax, ay), uuid=str(uuid.uuid4())))
                continue
            ang = {0: 180, 180: 0, 90: 270, 270: 90}[int(pn.position.angle) % 360]
            sch.labels.append(LocalLabel(text=net, position=Position(ax, ay, ang), effects=eff(), uuid=str(uuid.uuid4())))

    # power flags so ERC knows +5V and GND are driven
    flag = lib_symbol("power:PWR_FLAG")
    for k, net in enumerate(("+5V", "GND")):
        x, y = 40 + k * 20, 20
        inst = SchematicSymbol(libraryNickname="power", entryName="PWR_FLAG", position=Position(x, y, 0), unit=1, inBom=False,
                               onBoard=False, properties=[Property("Reference", "#FLG0%d" % (k + 1), 0, Position(x, y - 3, 0), eff(hide=True)),
                                                           Property("Value", "PWR_FLAG", 1, Position(x, y + 3, 0), eff())],
                               uuid=str(uuid.uuid4()))
        inst.pins = {"1": str(uuid.uuid4())}
        inst.instances = [SymbolProjectInstance(name="circuitpath-keychain",
                                                paths=[SymbolProjectPath(sheetInstancePath="/" + root, reference="#FLG0%d" % (k + 1), unit=1)])]
        sch.schematicSymbols.append(inst)
        pn = pins_of(flag)[0]
        sch.labels.append(LocalLabel(text=net, position=Position(x + pn.position.X, y - pn.position.Y, 0), effects=eff(), uuid=str(uuid.uuid4())))

    used = {}
    for p in D.PARTS:
        pass
    sch.libSymbols = [lib_symbol(s) for s in sorted({p["sym"] for p in D.PARTS} | {"power:PWR_FLAG"})]
    sch.to_file(out)
    print("wrote", out, len(sch.schematicSymbols), "symbols,", len(sch.labels), "labels")


if __name__ == "__main__":
    build(sys.argv[1])
