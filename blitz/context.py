# Storing what comes back
# ---------------------------------------------------------------------------

def find_lexicon(text: str) -> dict | None:
    """The lexicon inside a document, if it has one.

    Looks in fenced code blocks first, then at the whole document, so both
    a model's Markdown answer and a bare .yaml file work.
    """
    candidates = [m.group(1) for m in _FENCED.finditer(text)]
    candidates.append(text)
    for chunk in candidates:
        try:
            data = yaml.safe_load(chunk)
        except yaml.YAMLError:
            continue
        if isinstance(data, dict) and isinstance(data.get("dot_points"), dict):
            return data
    return None


def install_lexicon(subject_id: str, data: dict, root: Path | None = None,
                    design: StudyDesign | None = None) -> dict:
    """Validate a lexicon against the study design and write it.

    Ids the design does not have are dropped rather than written: they are
    almost always a lexicon built against a different version of the study
    design, and silently keeping them would file questions under dot points
    that have moved.
    """
    design = design or load_study_design(subject_id)
    valid = {kk.id for kk in design.all_key_knowledge()}
    entries = {k: v for k, v in (data.get("dot_points") or {}).items()}
    unknown = sorted(set(entries) - valid)
    kept = {k: v for k, v in entries.items() if k in valid}
    if not kept:
        raise ValueError(
            "none of the dot point ids in that lexicon belong to this study "
            f"design. It may have been written against a different version. "
            f"Unrecognised: {', '.join(unknown[:5])}"
            + (f" and {len(unknown) - 5} more" if len(unknown) > 5 else ""))

    out_dir = (Path(root) / "study-designs") if root else config.USER_DESIGN_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / f"{subject_id}-lexicon.yaml"
    doc = {"subject_id": subject_id, "dot_points": kept}
    header = (
        f"# Concept lexicon for {design.subject_name}.\n"
        f"# Installed by Blitz on {date.today():%d %b %Y} from a context "
        f"document.\n"
        f"# Study design fingerprint {fingerprint(design)}.\n"
        f"# See blitz/ingest/lexicon.py for how triggers, requires, avoid and\n"
        f"# weight are scored.\n\n")
    path.write_text(header + yaml.safe_dump(doc, sort_keys=False,
                                            allow_unicode=True, width=100),
                    encoding="utf-8")

    from .ingest.lexicon import load_lexicon

    load_lexicon.cache_clear()
    return {"path": str(path), "dot_points": len(kept),
            "coverage": round(len(kept) / max(len(valid), 1), 2),
            "unknown": unknown}


def add_context(subject_id: str, uploads: list[tuple[str, bytes]],
                root: Path | None = None,
                design: StudyDesign | None = None) -> dict:
    """Store context documents and install any lexicon they carry."""
    design = design or load_study_design(subject_id)
    folder = context_dir(subject_id, root)
    folder.mkdir(parents=True, exist_ok=True)
    stored: list[str] = []
    lexicon: dict | None = None
    notes: list[str] = []

    for filename, blob in uploads:
        name = Path(filename).name or "context.md"
        suffix = Path(name).suffix.lower()
        if suffix not in TEXTUAL:
            notes.append(f"{name}: not a text document, skipped "
                         f"({', '.join(sorted(TEXTUAL))} are read)")
            continue
        dest = folder / name
        dest.write_bytes(blob)
        stored.append(name)
        if lexicon is not None:
            continue
        try:
            text = blob.decode("utf-8")
        except UnicodeDecodeError:
            notes.append(f"{name}: not valid UTF-8 text, kept but not read")
            continue
        found = find_lexicon(text)
        if found is not None:
            try:
                lexicon = install_lexicon(subject_id, found, root, design)
                lexicon["from"] = name
            except ValueError as exc:
                notes.append(f"{name}: {exc}")

    if not stored:
        raise ValueError("nothing was stored. " + (notes[0] if notes else
                                                   "No files were uploaded."))
    if lexicon is None and not notes:
        notes.append("No concept lexicon found in these documents, so they are "
                     "kept as notes and tagging is unchanged. The briefing "
                     "questions ask for one as a fenced yaml block.")
    return {"subject_id": subject_id, "folder": str(folder), "stored": stored,
            "lexicon": lexicon, "notes": notes}


def list_context(subject_id: str, root: Path | None = None) -> list[dict]:
    folder = context_dir(subject_id, root)
    if not folder.is_dir():
        return []
    return [{"name": p.name, "bytes": p.stat().st_size}
            for p in sorted(folder.iterdir()) if p.is_file()]


def remove_context(subject_id: str, name: str, root: Path | None = None) -> bool:
    """Delete one stored context document. The lexicon it installed stays."""
    folder = context_dir(subject_id, root).resolve()
    path = (folder / Path(name).name).resolve()
    if path.parent != folder or not path.is_file():
        return False
    path.unlink()
    return True


def clear_lexicon(subject_id: str, root: Path | None = None) -> bool:
    """Remove an installed lexicon, back to word-overlap tagging."""
    out_dir = (Path(root) / "study-designs") if root else config.USER_DESIGN_DIR
    path = out_dir / f"{subject_id}-lexicon.yaml"
    if not path.is_file():
        return False
    shutil.move(path, path.with_suffix(".yaml.removed"))
    from .ingest.lexicon import load_lexicon

    load_lexicon.cache_clear()
    return True
